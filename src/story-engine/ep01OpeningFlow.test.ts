import { describe,expect,it } from "vitest";
import { initialRuntime,type Runtime,type Work } from "../schema";
import { completeEp01PlayerSetup } from "./ep01PlayerSetup";
import { showEp01Sighting,dismissEp01Sighting,advanceEp01Opening } from "./ep01Opening";
import { ep01OpeningChoices,sendEp01OpeningChoice,advanceEp01OpeningChoice } from "./ep01OpeningChoices";
import { ep01SecondChoices,sendEp01SecondChoice,advanceEp01SecondChoice } from "./ep01SecondChoices";
const work={id:"unpublished-lover-ep01",updatedAt:1,phone:{date:"2026-10-23",time:"22:31"},variables:{}} as Work;
const at=(s:Runtime,ms:number):Runtime=>({...s,elapsedMs:ms});
describe("EP01 approved opening through second-round integration",()=>{
 it.each(["A","B","C"])("preserves opening and nine-route availability for first branch %s",(branch)=>{
  let s=initialRuntime(work);
  s=completeEp01PlayerSetup(s,"안안","2005");
  s=showEp01Sighting(s);
  expect(ep01OpeningChoices(s)).toHaveLength(0);
  s=dismissEp01Sighting(s);
  for(let i=1;i<=5;i++)s=advanceEp01Opening(at(s,2000+i*800));
  expect(s.messages.kakao).toHaveLength(5);
  expect(ep01OpeningChoices(s)).toHaveLength(3);
  s=sendEp01OpeningChoice(s,"ep01-opening-choice-"+branch);
  const count=branch==="A"?4:3;
  for(let i=1;i<=count;i++)s=advanceEp01OpeningChoice(at(s,6000+i*2000));
  expect(s.variables.ep01OpeningReplyFinished).toBe(true);
  expect(ep01SecondChoices(s)).toHaveLength(3);
  s=sendEp01SecondChoice(s,ep01SecondChoices(s)[2].target);
  for(let i=1;i<=3;i++)s=advanceEp01SecondChoice(at(s,20000+i*2000));
  expect(s.variables.ep01SecondReplyFinished).toBe(true);
  expect(s.messages.kakao).toHaveLength(5+count+3);
  s=JSON.parse(JSON.stringify(s)) as Runtime;
  expect(advanceEp01SecondChoice(at(s,999999)).messages.kakao).toHaveLength(5+count+3);
 });
});
