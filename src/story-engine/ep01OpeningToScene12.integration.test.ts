import {describe,expect,it} from "vitest";
import {initialRuntime,type Runtime,type Work} from "../schema";
import {dismissEp01Sighting,showEp01Sighting,advanceEp01Opening} from "./ep01Opening";
import {ep01OpeningChoices,sendEp01OpeningChoice,advanceEp01OpeningChoice} from "./ep01OpeningChoices";
import {ep01SecondChoices,sendEp01SecondChoice,advanceEp01SecondChoice} from "./ep01SecondChoices";
import {advanceEp01BestFriend,ep01BestFriendChoices,sendEp01BestFriendChoice} from "./ep01BestFriend";
import {openScene10XPost,advanceScene10And11,scene10Choices,sendScene10Choice} from "./ep01Scene10And11";
import {scene12Choices} from "./ep01Scene12";
const work={id:"unpublished-lover-ep01",updatedAt:1,phone:{date:"2026-10-23",time:"22:31"},variables:{}} as Work;
const at=(s:Runtime,t:number):Runtime=>({...s,elapsedMs:t});
describe("EP01 full opening-to-scene12 playable gates",()=>{
 it("does not skip friend, X or scene11 on save/reload",()=>{
  let s:Runtime={...initialRuntime(work),variables:{ep01PlayerSetupDone:true}};
  s=dismissEp01Sighting(showEp01Sighting(s));
  for(let i=1;i<=5;i++)s=advanceEp01Opening(at(s,2000+i*800));
  s=sendEp01OpeningChoice(s,ep01OpeningChoices(s)[0].target);
  for(let i=1;i<=4;i++)s=advanceEp01OpeningChoice(at(s,6000+i*2000));
  s=sendEp01SecondChoice(s,ep01SecondChoices(s)[0].target);
  for(let i=1;i<=3;i++)s=advanceEp01SecondChoice(at(s,16000+i*2000));
  expect(s.variables.ep01SecondReplyFinished).toBe(true);
  expect(openScene10XPost(s,"ep01-rumor-1")).toBe(s);
  s=advanceEp01BestFriend(at(s,24000));
  expect(s.messages.kakao.at(-1)?.title).toBe("闺蜜");
  s=sendEp01BestFriendChoice(s,ep01BestFriendChoices(s)[0].target);
  for(let i=1;i<=3;i++)s=advanceEp01BestFriend(at(s,24000+i*2000));
  expect(s.variables.ep01XUnlocked).toBe(true);
  s=JSON.parse(JSON.stringify(s)) as Runtime;
  s=openScene10XPost(s,"ep01-rumor-1");
  s=openScene10XPost(s,"ep01-rumor-2");
  expect(s.variables.ep01Scene10StartedAt).toBeUndefined();
  s=openScene10XPost(s,"ep01-rumor-3");
  for(let i=1;i<=4;i++)s=advanceScene10And11(at(s,30000+i*2000));
  expect(scene10Choices(s)).toHaveLength(3);
  s=sendScene10Choice(s,scene10Choices(s)[1].target);
  expect(scene12Choices(s)).toHaveLength(0);
  for(let i=1;i<=4;i++)s=advanceScene10And11(at(s,38000+i*2000));
  expect(scene12Choices(s)).toHaveLength(3);
  const count=s.messages.kakao.length;
  s=JSON.parse(JSON.stringify(s)) as Runtime;
  s=advanceEp01BestFriend(advanceScene10And11(at(s,999999)));
  expect(s.messages.kakao).toHaveLength(count);
  expect(new Set(s.messages.kakao.map(m=>m.id)).size).toBe(count);
 });
});
